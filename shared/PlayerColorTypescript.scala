package monarchy.shared

object PlayerColorTypescript {
  def render: String = {
    val rows = PlayerColors.families.map { colors =>
      colors.map(color => s"'$color'").mkString("  [", ", ", "],")
    }.mkString("\n")
    s"""// Generated by bazel run //shared:generate-player-colors. Do not edit.
       |// Edit shared/PlayerColors.scala, then rerun the generator.
       |const shades = [
       |$rows
       |] as const;
       |
       |export const playerColorFamilies = shades.map(colors => ({ color: colors[${PlayerColors.representativeIndex}], colors }));
       |""".stripMargin
  }
}
