package monarchy.lib

object PlayerColorTypescript {
  def render: String = {
    val rows = Colors.families.map { colors =>
      colors.map(color => s"'$color'").mkString("  [", ", ", "],")
    }.mkString("\n")
    s"""// Generated by bazel run //lib:generate-player-colors. Do not edit.
       |// Edit lib/Colors.scala, then rerun the generator.
       |const shades = [
       |$rows
       |] as const;
       |
       |export const playerColorFamilies = shades.map(colors => ({ color: colors[${Colors.representativeIndex}], colors }));
       |""".stripMargin
  }
}
